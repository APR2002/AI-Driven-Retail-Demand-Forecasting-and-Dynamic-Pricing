# Ensure data is sorted by date
df = df.sort_values('date')

# Define features and target
X = df[
    [
        'price',
        'discount',
        'competitor_pricing',
        'inventory_level',
        'holiday_promotion',
        'lag_1_units_sold'
    ]
]

y = df['units_sold']

